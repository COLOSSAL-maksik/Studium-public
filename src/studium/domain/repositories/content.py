"""Teaching content storage contracts. Concrete owners retain FK identity."""

from typing import Protocol

from studium.domain.entities import StudiumEntity
from studium.domain.value_objects import EntityId, UtcInstant


class ContentRepository[T: StudiumEntity](Protocol):
    def list(self, *, include_deleted: bool = False) -> list[T]: ...
    def find_by_id(self, id: EntityId, *, include_deleted: bool = False) -> T | None: ...
    def insert(self, entity: T) -> None: ...
    def update(self, entity: T, *, expected_revision: int) -> None: ...
    def soft_delete(self, id: EntityId, *, expected_revision: int, at: UtcInstant) -> None: ...


class ContentLinkRepository[T: StudiumEntity](ContentRepository[T], Protocol):
    def for_owner(self, id: EntityId, *, include_deleted: bool = False) -> list[T]: ...
    def find_pair(self, owner_id: EntityId, target_id: EntityId) -> T | None: ...
